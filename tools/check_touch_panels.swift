import Foundation
import CoreGraphics

@main
enum TouchPanelChecks {
    static func main() {
        var checks = 0
        var failures = 0
        func expect(_ condition: Bool, _ message: String) {
            checks += 1
            if !condition { failures += 1; print("FAIL: \(message)") }
        }

        var panel = TouchPanelState(minimumExtent: 132, initialExtent: 240)
        panel.beginDrag()
        panel.updateDrag(translation: -70, maximumExtent: 500)
        expect(panel.extent == 170, "resize follows translation from touch-down")
        panel.endDrag(velocity: 0, maximumExtent: 500)
        expect(panel.extent == 170 && panel.rememberedExtent == 170, "slow resize retains arbitrary usable size")
        panel.setPresented(false, maximumExtent: 500)
        expect(panel.extent == 0, "close hides all library content")
        panel.setPresented(true, maximumExtent: 500)
        expect(panel.extent == 170, "normal opening restores remembered size")
        panel.beginDrag()
        panel.updateDrag(translation: -160, maximumExtent: 500)
        panel.endDrag(velocity: 0, maximumExtent: 500)
        expect(panel.extent == 0 && panel.rememberedExtent == 170, "slow close retains preceding usable size")
        panel.beginDrag()
        panel.updateDrag(translation: 20, maximumExtent: 500)
        panel.endDrag(velocity: 800, maximumExtent: 500)
        expect(panel.extent == 170, "opening flick restores remembered size")
        panel.beginDrag()
        panel.updateDrag(translation: -25, maximumExtent: 500)
        panel.endDrag(velocity: -800, maximumExtent: 500)
        expect(panel.extent == 0 && panel.rememberedExtent == 170, "closing flick preserves memory")
        panel.setPresented(true, maximumExtent: 500)
        panel.beginDrag()
        panel.updateDrag(translation: -5, maximumExtent: 500)
        panel.endDrag(velocity: -2000, maximumExtent: 500)
        expect(panel.extent == 165, "tiny movement does not become a closing flick")
        panel.beginDrag()
        panel.updateDrag(translation: -100, maximumExtent: 500)
        panel.cancelDrag()
        expect(panel.extent == 165 && panel.rememberedExtent == 165 && !panel.isDragging, "cancel restores size and memory")
        panel.beginDrag()
        panel.updateDrag(translation: .nan, maximumExtent: 500)
        expect(panel.extent == 165, "invalid translation is ignored")
        panel.updateDrag(translation: 20, maximumExtent: .infinity)
        expect(panel.extent == 165, "invalid available size is ignored")
        panel.endDrag(velocity: .nan, maximumExtent: 500)
        expect(panel.extent == 165 && !panel.isDragging, "invalid release cancels safely")

        for (travel, expected) in [(-100.0, 0.0), (-99, 132), (-34, 132), (-33, 132)] {
            var boundary = TouchPanelState(minimumExtent: 132, initialExtent: 165)
            boundary.beginDrag()
            boundary.updateDrag(translation: travel, maximumExtent: 500)
            boundary.endDrag(velocity: 0, maximumExtent: 500)
            expect(boundary.extent == expected, "half-minimum settlement at \(travel)")
        }

        var library = LibraryPanelState()
        library.updateViewport(width: 1112, height: 774, presented: true)
        expect(library.extent == 206 && library.maximumExtent == 206, "first opening reserves both compact decks")
        library.beginDrag()
        library.updateDrag(translation: -16)
        library.endDrag(velocity: 0)
        expect(library.extent == 190, "landscape size chosen directly")
        library.beginDrag()
        library.updateDrag(translation: -300)
        expect(!library.acceptsContentInput, "partly revealed header cannot receive touches")
        library.cancelDrag()
        expect(library.acceptsContentInput, "usable library accepts content input")
        library.updateViewport(width: 834, height: 1052, presented: true)
        expect(library.extent == 484, "portrait has its own initial extent")
        library.beginDrag()
        library.updateDrag(translation: -84)
        library.endDrag(velocity: 0)
        library.updateViewport(width: 1112, height: 774, presented: true)
        expect(library.extent == 190, "rotation restores landscape memory")
        library.setPresented(false)
        library.setPresented(true)
        expect(library.extent == 190, "toolbar close and open retain landscape size")
        library.adjust(by: -44)
        expect(library.extent == 146, "accessible adjustment changes size")
        library.setPresented(false)
        library.adjust(by: 44)
        expect(library.extent == 146, "accessible opening restores remembered size")
        library.adjust(by: -1000)
        expect(library.extent == 0, "accessible adjustment can close library")
        library.present(fullyExpanded: true)
        expect(library.extent == 206, "add-track expands an already-open library")
        library.beginDrag()
        library.updateDrag(translation: -56)
        library.endDrag(velocity: 0)
        library.present(fullyExpanded: true)
        expect(library.extent == 206, "repeated add-track expands after manual resize")
        library.setPresented(false)
        library.present(fullyExpanded: true)
        expect(library.extent == 206, "add-track expands a hidden library")
        library.updateViewport(width: 834, height: 1052, presented: true)
        expect(library.extent == 400, "landscape expansion does not overwrite portrait size")
        library.beginDrag()
        library.updateDrag(translation: -200)
        library.cancelDrag()
        expect(library.extent == 400, "library cancellation restores preceding extent")
        library.updateViewport(width: 1112, height: 774, presented: true)
        library.beginDrag()
        library.updateDrag(translation: -400)
        library.updateViewport(width: 834, height: 1052, presented: true)
        expect(library.extent == 400 && !library.isDragging, "rotation ends the old geometry gesture")
        library.updateViewport(width: 1112, height: 774, presented: true)
        expect(library.extent == 206, "rotation cancellation keeps preceding landscape extent")
        library.beginDrag()
        library.updateDrag(translation: -200)
        library.setPresented(false)
        library.updateDrag(translation: 100)
        library.endDrag(velocity: 800)
        expect(library.extent == 0 && !library.acceptsContentInput, "external close rejects stale drag updates")
        library.setPresented(true)
        expect(library.extent == 206, "external close preserves settled memory rather than drag preview")

        library.makeRoom(by: 40)
        expect(library.extent == 166 && library.acceptsContentInput, "a deck can borrow space while the browser stays usable")
        library.makeRoom(by: 1000)
        expect(library.extent == 132 && library.acceptsContentInput, "performance controls retain a usable browser minimum")
        library.makeRoom(by: .nan)
        library.makeRoom(by: -100)
        expect(library.extent == 132, "invalid space requests cannot move the browser")
        library.setPresented(false)
        library.makeRoom(by: 40)
        expect(library.extent == 0, "a space request cannot open a hidden browser")

        var shortcuts = LibraryPanelState()
        shortcuts.updateViewport(width: 834, height: 1052, presented: false)
        shortcuts.apply(.browse)
        expect(shortcuts.extent == 484 && shortcuts.selectedShortcut == .expand, "Browse shares usable portrait space evenly")
        expect(shortcuts.acceptsContentInput, "Browse exposes usable browser content")
        shortcuts.apply(.expand)
        expect(shortcuts.extent == 484 && shortcuts.selectedShortcut == .expand, "Expand fills portrait browser space")
        shortcuts.apply(.performance)
        expect(shortcuts.extent == 0 && shortcuts.selectedShortcut == .performance, "Performance hides the browser")
        expect(!shortcuts.acceptsContentInput, "Performance rejects hidden browser touches")
        shortcuts.setPresented(true)
        expect(shortcuts.extent == 484, "ordinary opening restores the preceding shortcut size")
        shortcuts.apply(.browse)
        shortcuts.beginDrag()
        shortcuts.updateDrag(translation: -54)
        shortcuts.endDrag(velocity: 0)
        expect(shortcuts.extent == 430 && shortcuts.selectedShortcut == nil, "manual resize remains free between shortcuts")
        shortcuts.apply(.performance)
        shortcuts.setPresented(true)
        expect(shortcuts.extent == 430, "Performance retains the manually chosen size")
        shortcuts.beginDrag()
        shortcuts.updateDrag(translation: -200)
        shortcuts.apply(.expand)
        shortcuts.updateDrag(translation: -400)
        shortcuts.endDrag(velocity: -800)
        expect(shortcuts.extent == 484 && !shortcuts.isDragging, "a shortcut rejects stale resize updates")
        shortcuts.apply(.browse)
        shortcuts.present(fullyExpanded: true)
        expect(shortcuts.extent == 484, "add-track still overrides Browse with maximum space")
        shortcuts.updateViewport(width: 1112, height: 774, presented: true)
        shortcuts.apply(.browse)
        expect(shortcuts.extent == 206, "Browse reserves both compact decks in landscape")
        shortcuts.apply(.performance)
        shortcuts.updateViewport(width: 834, height: 1052, presented: false)
        shortcuts.setPresented(true)
        expect(shortcuts.extent == 484, "landscape shortcuts preserve portrait memory")
        shortcuts.apply(.browse)
        shortcuts.updateViewport(width: 1112, height: 774, presented: true)
        expect(shortcuts.extent == 206, "rotation restores the previous landscape shortcut size")
        for (width, height, expected) in [(300.0, 250.0, 0.0), (100, 100, 0), (834, 400, 0)] {
            var small = LibraryPanelState()
            small.updateViewport(width: width, height: height, presented: false)
            small.apply(.browse)
            expect(small.extent == expected, "Browse clamps to constrained geometry")
            small.apply(.expand)
            expect(small.extent == small.maximumExtent, "Expand clamps to the viewport")
            small.apply(.performance)
            expect(small.extent == 0, "Performance closes in constrained geometry")
        }

        for (width, height) in [(1112.0, 774.0), (834, 1052), (880, 619), (619, 880)] {
            let baseline = PerformanceDockGeometry(width: width, height: height)
            let maximum = AdaptivePerformanceLayout.maximumLibraryExtent(available: height)
            for extent in [0.0, 20, 132, maximum / 2, maximum, maximum + 100] {
                let workspace = PerformanceWorkspaceGeometry(width: width, height: height, libraryExtent: extent)
                expect(workspace.dock.aButtons == baseline.aButtons && workspace.dock.bButtons == baseline.bButtons && workspace.dock.crossfader == baseline.crossfader,
                    "library motion cannot move dock")
                expect(workspace.libraryArea.height == min(maximum, extent), "extent controls actual browser height")
                expect(workspace.libraryArea.minY - workspace.deckArea.maxY == 44, "grab strip occupies its own 44-point lane")
                expect(workspace.deckArea.height >= 524, "full opening retains both complete compact decks and their divider")
                expect(workspace.libraryArea.maxY == height, "browser remains attached to bottom edge")
                expect(workspace.libraryArea.maxX <= baseline.workArea.maxX, "browser cannot cover dock")
            }
        }
        print("\(checks) panel and library checks; \(failures) failures")
        if failures > 0 { exit(1) }
    }
}
